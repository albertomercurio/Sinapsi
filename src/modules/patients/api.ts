import { computed, toValue, type MaybeRefOrGetter } from 'vue'
import { useMutation, useQuery, useQueryClient } from '@tanstack/vue-query'
import { supabase } from '@/shared/api/supabase'
import { unwrap } from '@/shared/api/errors'
import type { Patient, PatientCondition } from '@/shared/api/types'
import type { PatientUiPrefs } from '@/modules/activities/runtime/types'

export const patientKeys = {
  all: ['patients'] as const,
  list: (orgId: string | null, archived: boolean) => ['patients', 'list', orgId, archived] as const,
  one: (id: string) => ['patients', 'one', id] as const,
  conditions: (id: string) => ['patients', 'conditions', id] as const,
}

export interface PatientListRow extends Patient {
  patient_conditions: Pick<PatientCondition, 'category'>[]
  sessions: { scheduled_for: string; status: string }[]
}

export function usePatients(
  orgId: MaybeRefOrGetter<string | null>,
  archived: MaybeRefOrGetter<boolean> = false,
) {
  return useQuery({
    queryKey: computed(() => patientKeys.list(toValue(orgId), toValue(archived))),
    enabled: computed(() => !!toValue(orgId)),
    queryFn: async () => {
      let q = supabase
        .from('patients')
        .select('*, patient_conditions(category), sessions(scheduled_for, status)')
        .eq('org_id', toValue(orgId)!)
        .order('code')
      q = toValue(archived) ? q.not('archived_at', 'is', null) : q.is('archived_at', null)
      return unwrap(await q) as unknown as PatientListRow[]
    },
  })
}

export function usePatient(id: MaybeRefOrGetter<string>) {
  return useQuery({
    queryKey: computed(() => patientKeys.one(toValue(id))),
    enabled: computed(() => !!toValue(id)),
    queryFn: async () =>
      unwrap(await supabase.from('patients').select('*').eq('id', toValue(id)).single()),
  })
}

export function usePatientConditions(id: MaybeRefOrGetter<string>) {
  return useQuery({
    queryKey: computed(() => patientKeys.conditions(toValue(id))),
    queryFn: async () =>
      unwrap(
        await supabase
          .from('patient_conditions')
          .select('*')
          .eq('patient_id', toValue(id))
          .order('created_at'),
      ),
  })
}

export interface PatientInput {
  /** End-to-end encrypted "first + last name" (v1.iv.ciphertext), or null. */
  name_enc?: string | null
  birth_year: number | null
  sex: 'F' | 'M' | 'X' | null
  education_years: number | null
  handedness: 'right' | 'left' | 'ambi' | null
  content_locale: string
  notes: string | null
  target_success: number
  ui_prefs: PatientUiPrefs
}

export function useCreatePatient() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (input: PatientInput & { org_id: string }) =>
      // `code` is generated by the database (the client has no privilege to set it).
      unwrap(
        await supabase
          .from('patients')
          .insert(input as never)
          .select('*')
          .single(),
      ),
    onSuccess: () => qc.invalidateQueries({ queryKey: patientKeys.all }),
  })
}

export function useUpdatePatient() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async ({
      id,
      patch,
    }: {
      id: string
      patch: Partial<PatientInput> & { archived_at?: string | null }
    }) =>
      unwrap(
        await supabase
          .from('patients')
          .update(patch as never)
          .eq('id', id)
          .select('*')
          .single(),
      ),
    onSuccess: (p) => {
      qc.setQueryData(patientKeys.one(p.id), p)
      void qc.invalidateQueries({ queryKey: ['patients', 'list'] })
    },
  })
}

export function useDeletePatient() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async ({ id, code }: { id: string; code: string }) =>
      unwrap(await supabase.rpc('delete_patient', { p_patient: id, p_confirm_code: code })),
    onSuccess: () => qc.invalidateQueries({ queryKey: patientKeys.all }),
  })
}

export function useAddCondition() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (c: {
      patient_id: string
      category: string
      icd11_code: string | null
      onset_year: number | null
      notes: string | null
    }) =>
      unwrap(
        await supabase
          .from('patient_conditions')
          .insert(c as never)
          .select('*')
          .single(),
      ),
    onSuccess: (c) => qc.invalidateQueries({ queryKey: patientKeys.conditions(c.patient_id) }),
  })
}

export function useRemoveCondition() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (c: { id: string; patient_id: string }) => {
      unwrap(await supabase.from('patient_conditions').delete().eq('id', c.id))
      return c
    },
    onSuccess: (c) => qc.invalidateQueries({ queryKey: patientKeys.conditions(c.patient_id) }),
  })
}

/**
 * Everything stored about one patient (GDPR art. 15/20 access & portability),
 * as a JSON document. The export is logged in the audit trail.
 */
export async function exportPatientData(
  patient: Patient,
  name: { first: string; last: string } | null = null,
) {
  const [conditions, sessions, items, runs, abilities] = await Promise.all([
    supabase.from('patient_conditions').select('*').eq('patient_id', patient.id),
    supabase.from('sessions').select('*').eq('patient_id', patient.id),
    supabase
      .from('session_items')
      .select('*, sessions!inner(patient_id)')
      .eq('sessions.patient_id', patient.id),
    supabase.from('activity_runs').select('*').eq('patient_id', patient.id).order('started_at'),
    supabase.from('patient_ability').select('*').eq('patient_id', patient.id),
  ])
  const doc = {
    format: 'sinapsi-patient-export',
    version: 1,
    exported_at: new Date().toISOString(),
    // Decrypted in the browser for the export; the server only holds name_enc.
    patient: { ...patient, name: name ?? undefined },
    conditions: unwrap(conditions),
    sessions: unwrap(sessions),
    session_items: (unwrap(items) as Record<string, unknown>[]).map(
      ({ sessions: _s, ...rest }) => rest,
    ),
    activity_runs: unwrap(runs),
    patient_ability: unwrap(abilities),
  }
  await supabase.rpc('log_event', {
    p_org: patient.org_id,
    p_action: 'export',
    p_entity: 'patients',
    p_entity_id: patient.id,
    p_details: { code: patient.code },
  })
  return doc
}
